#!/usr/bin/env python3
"""Step 8 — install each selected repository's use-hpc configuration into its clone.

    use-hpc-eval configure [repo_id ...]

The configuration of repository <id> (owner__name) is versioned here, in configs/<id>/:
  experiments.json   the experiment graph written with the use-hpc skill (stages, cells, steps, contracts, results)
  requirements.txt   Python packages for the jobs (wheelhouse first; extras from the shared wheel directory)
  hooks/<stage>.sh   optional service hooks; "ollama" or "vllm" in hooks.txt copies common/<name>.sh per stage
  reported.csv       numbers the paper reports for the reproduced subset (metric, setting, value, source table/page)
  compare.py         turns the run's outputs into results/compare/measured.csv (same keys as reported.csv)
cluster.env is generated (account, modules, scratch paths, shared wheel directory). The clone's hpc/ gets a copy;
then `bash hpc/scripts/selftest.sh` must pass before anything is submitted.
"""
from __future__ import annotations

import json
import shutil
import subprocess
import sys
from pathlib import Path

from use_hpc_eval import config as C

CONFIGS = C.CONFIGS
COMMON = C.COMMON
WHEELS = C.WORK / "wheels"
CLUSTER_ENV = """# generated by use-hpc-eval configure (s08)
ACCOUNT="${{ACCOUNT:-def-mbabaei}}"
MAIL_TYPE="FAIL"
MAX_REQUEUES=20
REQUEUE_SIGNAL_SECS=900
MODULES="{modules}"
EXTRA_WHEELS="{wheels}"
SRC_DIRS="{src_dirs}"
CODE_HASH_DIRS="{hash_dirs}"
WORK="{work}"
RESULTS_DEST=""
GPU_MONITOR_SECS=60
HF_HOME="{hf}"
HF_HUB_CACHE="{hf}/hub"
OLLAMA_MODELS="${{SCRATCH}}/.ollama/models"
OLLAMA_PREFIX="${{SCRATCH}}/autom2m_hpc/opt/ollama-0.30.6"
REPRO_ID="{rid}"
"""


def install(rid: str) -> None:
    src = CONFIGS / rid
    repo = C.WORK / "repos" / rid
    hpc = repo / "hpc" / "config"
    exp = json.loads((src / "experiments.json").read_text())
    meta = exp.get("_repro", {})
    (hpc / "cluster.env").write_text(CLUSTER_ENV.format(
        modules=meta.get("modules", "StdEnv/2023 python/3.11 arrow/24.0.0"), wheels=WHEELS,
        src_dirs=meta.get("src_dirs", "."), hash_dirs=meta.get("hash_dirs", "."),
        work=C.WORK / "runs" / rid, hf=C.WORK / "hf_cache", rid=rid))
    shutil.copy(src / "experiments.json", hpc / "experiments.json")
    shutil.copy(src / "requirements.txt", hpc / "requirements.txt")
    hooks = repo / "hpc" / "slurm" / "hooks"
    if (src / "hooks.txt").exists():
        for line in (src / "hooks.txt").read_text().split("\n"):
            if line.strip() and not line.startswith("#"):
                stage, name = line.split()
                text = (COMMON / f"{name}.sh").read_text()
                pre = (src / "hooks" / f"{stage}.pre.sh")
                (hooks / f"{stage}.sh").write_text((pre.read_text() if pre.exists() else "") + text)
    if (src / "hooks").is_dir():
        for h in (src / "hooks").glob("*.sh"):
            if not h.name.endswith(".pre.sh"):
                shutil.copy(h, hooks / h.name)
    shutil.copy(COMMON / "compare_lib.py", repo / "hpc" / "compare_lib.py")
    for extra in list(src.glob("*.py")) + list(src.glob("*.csv")):     # compare.py, glue_*.py, reported.csv
        shutil.copy(extra, repo / "hpc" / extra.name)
    r = subprocess.run(["bash", str(repo / "hpc" / "scripts" / "selftest.sh")], capture_output=True, text=True)
    print(f"{rid:<40} selftest {'OK' if r.returncode == 0 else 'FAILED'}")
    if r.returncode:
        print("\n".join(l for l in r.stdout.splitlines() if "FAIL" in l))


def main() -> int:
    ids = sys.argv[1:] or sorted(p.name for p in CONFIGS.iterdir() if (p / "experiments.json").exists())
    WHEELS.mkdir(parents=True, exist_ok=True)
    for rid in ids:
        install(rid)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
